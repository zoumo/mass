import { expect, test } from '@playwright/test'

test('production Router page, URL selection, safety, keyboard and navigation', async ({ page, baseURL }) => {
  const errors: string[] = []
  const unexpectedRequests: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (new URL(request.url()).origin !== baseURL || !['GET', 'HEAD'].includes(request.method())) unexpectedRequests.push(request.url())
    expect(request.headers()['authorization']).toBeUndefined()
  })
  await page.goto('/observer/routers?refresh=paused')
  await expect(page.getByRole('link', { name: 'Alpha Router', exact: true })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Beta Router', exact: true })).toBeVisible()
  await expect(page.getByText('尚未建立 Session', { exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('link', { name: 'Beta Router', exact: true }).click()
  await expect(page).toHaveURL(/selected=beta/)
  await expect(page.getByRole('heading', { name: 'Beta Router', exact: true })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Beta Router', exact: true })).toBeVisible()
  await page.goBack()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('combobox', { name: '项目', exact: true }).click()
  await page.getByRole('option', { name: 'Alpha', exact: true }).click()
  await expect(page).toHaveURL(/project=alpha/)
  await expect(page.getByRole('link', { name: 'Beta Router', exact: true })).toHaveCount(0)
  await page.getByRole('link', { name: 'Alpha Router', exact: true }).click()
  await page.getByRole('tab', { name: '处理配置', exact: true }).click()
  await page.getByText('Router 任务指引', { exact: true }).click()
  await expect(page.locator('pre')).toContainText('<img src=')
  await expect(page.locator('pre')).toContainText('[redacted]')
  await expect(page.locator('main img')).toHaveCount(0)
  expect(await page.locator('body').innerText()).not.toContain('fixture-memory-secret')
  await page.getByRole('button', { name: '关闭详情', exact: true }).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('button', { name: '继续自动刷新' }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('button', { name: '暂停自动刷新' })).toHaveAttribute('aria-pressed', 'false')
  await page.getByRole('button', { name: '暂停自动刷新' }).click()
  await page.getByRole('link', { name: '工作项', exact: true }).click()
  await expect(page.getByRole('heading', { name: '工作项', exact: true })).toBeVisible()
  await page.getByRole('link', { name: '路由器', exact: true }).click()
  await expect(page).toHaveURL(/project=alpha/)
  await page.screenshot({ path: 'test-results/routers-desktop.png', fullPage: true })
  expect(errors).toEqual([])
  expect(unexpectedRequests).toEqual([])
})

test('loading, empty, query failure, stale cache and recovery', async ({ page }) => {
  let release: (() => void) | undefined
  const gate = new Promise<void>(resolve => { release = resolve })
  await page.route('**/observer/api/routers?*', async route => { await gate; await route.continue() })
  await page.goto('/observer/routers?refresh=paused')
  await expect(page.getByRole('heading', { name: '正在读取 Routers' })).toBeVisible()
  release?.()
  await expect(page.getByRole('link', { name: 'Alpha Router', exact: true })).toBeVisible()
  await page.unroute('**/observer/api/routers?*')
  await page.route('**/observer/api/routers?*', route => route.fulfill({ status: 503, body: 'unavailable' }))
  await page.getByRole('button', { name: '刷新查询', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Router 查询失败 · stale' })).toBeVisible()
  await expect(page.getByRole('link', { name: 'Alpha Router', exact: true })).toBeVisible()
  await page.unroute('**/observer/api/routers?*')
  await page.getByRole('button', { name: '重试查询', exact: true }).click()
  await expect(page.getByRole('heading', { name: 'Router 查询失败 · stale' })).toHaveCount(0)
  await page.route('**/observer/api/routers?*', route => route.fulfill({ json: { items: [], observedAt: new Date().toISOString(), source: 'loaded_config' } }))
  await page.goto('/observer/routers?project=beta&refresh=paused')
  await expect(page.getByRole('heading', { name: '当前筛选没有 Router' })).toBeVisible()
  await page.getByRole('link', { name: '清除 Project 筛选' }).click()
  await page.unroute('**/observer/api/routers?*')
  await page.getByRole('button', { name: '刷新查询', exact: true }).click()
  await expect(page.getByRole('link', { name: 'Alpha Router', exact: true })).toBeVisible()
  await page.route('**/observer/api/routers?*', route => route.fulfill({ status: 503, body: 'unavailable' }))
  await page.reload()
  await expect(page.getByRole('heading', { name: 'Router 查询失败', exact: true })).toBeVisible()
})

test('narrow layout preserves identity and touch targets', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await page.goto('/observer/routers?refresh=paused&selected=alpha')
  await expect(page.getByRole('heading', { name: 'Alpha Router', exact: true })).toBeVisible()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
  const button = await page.getByRole('dialog').getByRole('button', { name: '刷新查询' }).boundingBox()
  expect(button?.height).toBeGreaterThanOrEqual(44)
  await page.keyboard.press('Escape')
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.getByRole('link', { name: '跳到主要内容' }).focus()
  await expect(page.getByRole('link', { name: '跳到主要内容' })).toBeFocused()
  await page.keyboard.press('Enter')
  await expect(page.locator('#main')).toBeFocused()
  await page.screenshot({ path: 'test-results/routers-mobile.png', fullPage: true })
})


test('Aura components remain styled under the production CSP', async ({ page }) => {
  const violations: string[] = []
  let phase = 'initial list'
  page.on('console', message => { if (message.text().includes('Content Security Policy')) violations.push(`${phase}: ${message.text()}`) })
  const response = await page.goto('/observer/triggers?project=alpha&refresh=paused')
  expect(response?.headers()['content-security-policy']).toContain("style-src 'self'")
  await expect(page.getByRole('link', { name: 'Router 后交 Worker', exact: true })).toBeVisible()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await page.screenshot({ path: 'test-results/events-list-aura.png', fullPage: true })
  phase = 'open Drawer'
  await page.getByRole('link', { name: 'Router 后交 Worker', exact: true }).click()
  const drawer = page.getByRole('dialog')
  await expect(drawer).toBeVisible()
  // A blank/transparent Drawer catches the CSP regression that functional text checks miss.
  expect(await drawer.evaluate(el => getComputedStyle(el).backgroundColor)).not.toBe('rgba(0, 0, 0, 0)')
  expect(await drawer.locator('.p-tablist-tab-list').evaluate(el => getComputedStyle(el).display)).toBe('flex')
  await page.screenshot({ path: 'test-results/event-overview-aura.png' })
  phase = 'close Drawer'
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  phase = 'open filters'
  await page.getByRole('button', { name: '更多筛选', exact: true }).click()
  phase = 'open Select'
  await page.getByRole('combobox', { name: '决定', exact: true }).click()
  await expect(page.getByRole('option', { name: 'ignored', exact: true })).toBeVisible()
  await page.getByRole('option', { name: 'ignored', exact: true }).click()
  await page.keyboard.press('Escape')
  await expect(page.getByRole('form', { name: '更多事件筛选' })).toHaveCount(0)
  phase = 'field explanation'
  await page.locator('th span[tabindex]').scrollIntoViewIfNeeded()
  await page.locator('th span[tabindex]').focus()
  await test.info().attach('csp-style-injection-attempts.json', { body: JSON.stringify(violations), contentType: 'application/json' })
  await expect(page.locator('th span[tabindex]')).toHaveAttribute('title', '路由入口、业务决定与固定投递分别记录；关联工作不代表已执行。')
  expect(violations).toEqual([])
})
