// Huma's factory is process-global. Set it once at package initialization, never
// during request handling or server construction (multiple servers may coexist).
func init() {
	huma.NewError = func(status int, _ string, _ ...error) huma.StatusError {
		if status == 422 {
			status = 400
		}
		public := Invalid()
		if status == 408 {
			status = 504
			public = &Error{Code: "deadline_exceeded", Reason: "body_read_timeout", Message: "Request body was not received before the deadline"}
		} else if status >= 500 {
			public = &Error{Code: "internal", Reason: "http_failure", Message: "HTTP request could not be processed"}
		}
		return &responseError{public: public, status: status}
	}
}

type responseError struct {
	public *Error
	status int
}

func (e *responseError) Error() string                { return e.public.Error() }
func (e *responseError) GetStatus() int               { return e.status }
func (e *responseError) MarshalJSON() ([]byte, error) { return json.Marshal(e.public) }
func (e *responseError) Schema(r huma.Registry) *huma.Schema {
	return r.Schema(reflect.TypeFor[Error](), true, "")
}

func (s *Server) routes() (http.Handler, huma.API) {
	router := chi.NewRouter()
	router.Use(s.guard)
	router.NotFound(func(w http.ResponseWriter, r *http.Request) {
		fail(w, 404, &Error{Code: "not_found", Reason: "route_not_found", Message: "Route not found"})
	})
	router.MethodNotAllowed(func(w http.ResponseWriter, r *http.Request) {
		for _, method := range []string{"GET", "POST", "PUT", "DELETE", "PATCH", "HEAD", "OPTIONS"} {
			if router.Match(chi.NewRouteContext(), method, r.URL.EscapedPath()) {
				w.Header().Add("Allow", method)
			}
		}
		fail(w, 405, Invalid())
	})
	cfg := huma.DefaultConfig("MASS HTTP API", "v1")
	cfg.CreateHooks = nil
	cfg.OpenAPIPath = ""
	cfg.DocsPath = ""
	cfg.SchemasPath = ""
	cfg.RejectUnknownQueryParameters = true
	format := huma.Format{Marshal: func(w io.Writer, v any) error { return json.NewEncoder(w).Encode(v) }, Unmarshal: decodeJSON}
	cfg.Formats = map[string]huma.Format{"application/json": format, "json": format}
	cfg.Components.SecuritySchemes = map[string]*huma.SecurityScheme{"bearerAuth": {Type: "http", Scheme: "bearer"}}
	api := humachi.New(router, cfg)
	api.UseMiddleware(protocol)
	registerWorkSchemas(api.OpenAPI().Components.Schemas)
	s.registerRuntimes(api)
	s.registerSessions(api)
	for _, probe := range []string{"livez", "readyz"} {
		state := "alive"
		if probe == "readyz" {
			state = "ready"
		}
		register(api, huma.Operation{Method: "GET", Path: "/" + probe, OperationID: probe}, func(context.Context, *noInput) (*probeOutput, error) {
			return &probeOutput{Body: probeStatus{Status: state}}, nil
		})
	}
	return router, api
}

// OpenAPI registers the same typed operations as a server, without Service,
// Store, listeners, credentials or Agent initialization.
func OpenAPI() ([]byte, error) {
	_, api := (&Server{}).routes()
	return json.MarshalIndent(api.OpenAPI(), "", "  ")
}

type (
	noInput     struct{}
	probeStatus struct {
		Status string `json:"status"`
	}
)
type probeOutput struct{ Body probeStatus }

func register[I, O any](api huma.API, op huma.Operation, handler func(context.Context, *I) (*O, error)) {
	op.MaxBodyBytes = -1
	op.BodyReadTimeout = -1
	if strings.HasPrefix(op.Path, "/apis/") {
		op.Security = []map[string][]string{{"bearerAuth": {}}}
	}
	// All errors share the domain error schema, including failures generated by
	// middleware. Do not let Huma add its default problem+json schema.
	if op.Responses == nil {
		op.Responses = map[string]*huma.Response{}
	}
	schema := api.OpenAPI().Components.Schemas.Schema(reflect.TypeFor[Error](), true, "")
	for _, status := range []string{"400", "401", "403", "404", "405", "406", "409", "415", "422", "429", "500", "503", "504", "default"} {
		op.Responses[status] = &huma.Response{Description: "Operation error", Content: map[string]*huma.MediaType{"application/json": {Schema: schema}}}
	}
	huma.Register(api, op, func(ctx context.Context, in *I) (*O, error) {
		value, err := handler(ctx, in)
		if err != nil {
			return nil, asHTTPError(err)
		}
		if err = validateOutput(reflect.ValueOf(value)); err != nil {
			return nil, &responseError{public: &Error{Code: "internal", Reason: "encoding_failed", Message: "Response could not be encoded"}, status: 500}
		}
		return value, nil
	})
}

func asHTTPError(err error) error {
	var protocol *protocolError
	if errors.As(err, &protocol) {
		return &responseError{public: protocol.public, status: protocol.status}
	}
	p := PublicError(err)
	return &responseError{public: p, status: statusFor(p.Code)}
}

func decodeJSON(b []byte, out any) error {
	if !utf8.Valid(b) {
		return Invalid()
	}
	if err := validateJSON(b); err != nil {
		return err
	}
	d := json.NewDecoder(bytes.NewReader(b))
	d.UseNumber()
	var value any
	if err := d.Decode(&value); err != nil {
		return Invalid()
	}
	if err := validateShape(value, reflect.TypeOf(out).Elem()); err != nil {
		return err
	}
	d = json.NewDecoder(bytes.NewReader(b))
	d.UseNumber()
	d.DisallowUnknownFields()
	if err := d.Decode(out); err != nil {
		return Invalid()
	}
	return nil
}

// guard runs before routing, so aliases and unknown resources cannot bypass
// authentication. Probes report process/admission health only.
func (s *Server) guard(next http.Handler) http.Handler {
	return http.HandlerFunc(func(w http.ResponseWriter, r *http.Request) {
		w.Header().Set("Cache-Control", "no-store")
		// chi prefers RawPath when present. Always supply the escaped path so a
		// canonical %25 escape cannot fall back to an already-decoded URL.Path.
		requestURL := *r.URL
		requestURL.RawPath = r.URL.EscapedPath()
		r = r.Clone(r.Context())
		r.URL = &requestURL
		if hasBody(r) {
			defer r.Body.Close()
		}
		probe := r.URL.Path == "/livez" || r.URL.Path == "/readyz"
		if !probe && !s.authorized(r) {
			fail(w, 401, &Error{Code: "unauthenticated", Reason: "invalid_credentials", Message: "Valid instance credentials required"})
			return
		}
		if (!probe || r.URL.Path == "/readyz" && r.Method == http.MethodGet) && !s.ready.Load() {
			fail(w, 503, &Error{Code: "unavailable", Reason: "not_ready", Message: "API admission is closed"})
			return
		}
		if _, ok := r.Header["Idempotency-Key"]; ok {
			fail(w, 400, Invalid())
			return
		}
		if (r.Method == http.MethodGet || r.Method == http.MethodDelete || r.Method == http.MethodHead) && hasBody(r) {
			fail(w, 400, Invalid())
			return
		}
		next.ServeHTTP(w, r)
	})
}

func protocol(ctx huma.Context, next func(huma.Context)) {
	r, w := humachi.Unwrap(ctx)
	reject := func(status int) { fail(w, status, Invalid()) }
	media := "application/json"
	if strings.HasSuffix(ctx.Operation().Path, "/events/stream") {
		media = "text/event-stream"
		if _, ok := w.(http.Flusher); !ok {
			fail(w, 503, &Error{Code: "unavailable", Reason: "stream_unavailable", Message: "Streaming unavailable"})
			return
		}
		for _, v := range r.Header.Values("Last-Event-ID") {
			if v != "" {
				reject(400)
				return
			}
		}
	}
	if !accepts(r.Header.Get("Accept"), media) {
		reject(406)
		return
	}
	if hasBody(r) {
		kind, params, err := mime.ParseMediaType(r.Header.Get("Content-Type"))
		if err != nil || kind != "application/json" || (params["charset"] != "" && !strings.EqualFold(params["charset"], "utf-8")) {
			reject(415)
			return
		}
	}
	q, err := url.ParseQuery(r.URL.RawQuery)
	if err != nil {
		reject(400)
		return
	}
	for key, values := range q {
		declared := false
		multiple := false
		for _, p := range ctx.Operation().Parameters {
			if p.In == "query" && p.Name == key {
				declared = true
				multiple = p.Schema.Type == "array"
			}
		}
		if !declared || (!multiple && len(values) != 1) {
			reject(400)
			return
		}
		for _, v := range values {
			if v == "" || !utf8.ValidString(v) {
				reject(400)
				return
			}
		}
	}
	if limit := q.Get("limit"); limit != "" {
		for _, c := range limit {
			if c < '0' || c > '9' {
				reject(400)
				return
			}
		}
	}
	if err := r.Context().Err(); err != nil {
		fail(w, 504, &Error{Code: "deadline_exceeded", Reason: "request_expired", Message: "Request expired before dispatch"})
		return
	}
	next(ctx)
}
