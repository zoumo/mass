test('a missing Session name never becomes a name inferred from namespace', async ({ page }) => {
 await page.route('**/observer/api/tickets/t03-root?*', async route => {
  const response = await route.fetch()
  const ticket = await response.json()
  for (const assignment of ticket.assignments) {
   if (assignment.observation.session) {
    assignment.observation.session.name = ''
    assignment.observation.session.namespace = 'namespace-is-not-a-name'
   }
  }
  await route.fulfill({ response, json: ticket })
 })
 await page.goto('/observer/tickets?project=alpha&selected=t03-root&selectedProject=alpha&refresh=paused')
 const detail = page.getByRole('region', { name: 'Ticket 责任详情' })
 const session = detail.getByRole('region', { name: '当前负责会话' })
 await expect(session.getByRole('link', { name: '查看会话', exact: true })).toHaveAttribute('href', /selected=t03-session-new/)
 await expect(detail).not.toContainText('namespace-is-not-a-name')
 await detail.getByRole('tab', { name: '派工与委派' }).click()
 await detail.locator('#assignment-t03-old').click()
 await expect(detail.locator('details[data-reading="assignment-t03-old"]').getByRole('link', { name: '查看会话', exact: true })).toHaveAttribute('href', /selected=t03-session&/)
})


