import { expect, test } from '@playwright/test'

const endpoint = `http://127.0.0.1:${process.env.SUPERAGENT_ROUTING_BROWSER_PORT || '18794'}`
type Event = { id: string; kind: string; issueId?: string; messageId?: string; deliveryId?: string; at: string; status?: string; title?: string; summary?: string; bindingId?: string }

test('Topic activity opens source facts, pages both categories and restores the filter', async ({ page, request }, info) => {
  const topics = await (await request.get(endpoint + '/v1/observer/topics')).json()
  const topic = topics.items.find((t: {title: string}) => t.title === 'Observer routing Topic')
  const activityURL = endpoint + '/v1/observer/topic-activity?topicId=' + topic.id
  const all: Event[] = (await (await request.get(activityURL + '&limit=200')).json()).items
  const pageSize = 10
  expect(all.length).toBeGreaterThan(pageSize)
  const methods = new Set<string>()
  page.on('request', req => { if (req.url().includes('/v1/')) methods.add(req.method()) })
  await page.setViewportSize({width:1360,height:900})
  await page.goto(endpoint + '/observer/?perspective=topic&id=' + topic.id)
  await page.getByRole('button', {name:'暂停自动刷新'}).click()
  const detail = page.getByRole('article', {name:'当前 Topic'})
  const feed = detail.getByRole('region', {name:'活动流',exact:true})
  const rows = feed.locator('.topic-feed > li')
  await expect(detail.getByRole('heading', {name:topic.title})).toBeVisible()
  await expect(detail.locator('.topic-goal')).toContainText(topic.goal)
  await expect(rows).toHaveCount(pageSize)
  await expect(rows.locator('time')).toHaveCount(pageSize)
  expect(await rows.locator('time').evaluateAll(nodes => nodes.map(n => n.getAttribute('datetime')))).toEqual(all.slice(0,pageSize).map(e => e.at))
  await feed.getByRole('button', {name:'加载更多活动'}).click()
  await expect(rows).toHaveCount(all.length)
  expect(await rows.evaluateAll(nodes => nodes.map(n => n.getAttribute('data-kind')))).toEqual(all.map(e => e.kind))
  await page.evaluate(() => window.scrollTo(0,0))
  await page.screenshot({path:info.outputPath('topic-mixed-desktop.png'),animations:'disabled'})

  const filter = feed.getByRole('navigation', {name:'筛选活动'})
  await filter.getByRole('link', {name:'消息',exact:true}).click()
  const returned = rows.filter({has: page.locator('summary strong', {hasText:'Topic 退回'})})
  await returned.locator('summary').focus()
  await page.keyboard.press('Enter')
  await expect(returned.getByText('Observer return reason')).toBeVisible()
  await expect(returned.getByText('Original input observer-routing', {exact:true}).last()).toBeVisible()
  const messageId = all.find(e=>e.kind==='route_request')!.messageId
  await expect(returned.getByRole('link',{name:'查看此消息'})).toHaveAttribute('href',new RegExp(messageId!))
  await expect(returned.getByRole('link',{name:'查看原投递'})).toBeVisible()
  await page.screenshot({path:info.outputPath('topic-return.png'),fullPage:true,animations:'disabled'})
  await expect(rows.filter({hasText:'Session 已受理'}).first()).toBeVisible()
  await page.getByRole('button',{name:'刷新',exact:true}).click()
  await expect(returned.getByText('Observer return reason')).toBeVisible()

  await filter.getByRole('link',{name:'Issue',exact:true}).click()
  const report = feed.locator('li[data-kind=report_submitted]').filter({hasText:'Sample build verified'})
  await report.locator('summary').click()
  await expect(report.getByText('Worker',{exact:true})).toBeVisible()
  await expect(report.getByText('Build exited with code 0.')).toBeVisible()
  await expect(report.getByRole('link',{name:'查看此消息'})).toHaveCount(0)
  const acceptance = feed.locator('li[data-kind=completion]').first()
  await acceptance.locator('summary').click()
  await expect(acceptance.getByText('Reviewed the sample build log')).toBeVisible()
  await expect(acceptance.getByText('artifacts/build.log')).toBeVisible()
  const snapshot = feed.locator('li[data-kind=issue_snapshot]').first()
  await snapshot.locator('summary').click()
  await expect(snapshot.getByText('Confirm the archive with the reviewer')).toBeVisible()
  const requirement = feed.locator('li[data-kind=goal_notification]').first()
  await requirement.locator('summary').click()
  await expect(requirement.getByText('记录的目标版本')).toBeVisible()
  const filtersURL = page.url()
  await page.reload()
  await expect(filter.getByRole('link',{name:'Issue',exact:true})).toHaveAttribute('aria-current','true')
  await report.locator('summary').click()
  await report.getByRole('link',{name:'查看此 Issue'}).click()
  await expect(page).toHaveURL(/perspective=issue/)
  await page.goBack()
  await expect(page).toHaveURL(filtersURL)
  await expect(filter.getByRole('link',{name:'Issue',exact:true})).toHaveAttribute('aria-current','true')
  await page.setViewportSize({width:390,height:844})
  await expect(detail).toBeVisible()
  await expect(feed.locator('li[data-kind=report_submitted]').first()).toBeVisible()
  await page.evaluate(() => window.scrollTo(0,0))
  expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390)
  await page.screenshot({path:info.outputPath('topic-issue-narrow.png'),animations:'disabled'})
  await detail.getByRole('link',{name:'查看 Session'}).click()
  await expect(page.getByRole('dialog')).toContainText('MASS Session')
  expect([...methods]).toEqual(['GET'])
})

test('Topic activity retries a failed read without reporting an empty history', async ({page,request}) => {
  const {items:[topic]} = await (await request.get(endpoint + '/v1/observer/topics')).json()
  await page.route('**/v1/observer/topic-activity?**', route=>route.fulfill({status:503,body:'{}'}))
  await page.goto(endpoint + '/observer/?perspective=topic&id=' + topic.id)
  const feed = page.getByRole('region',{name:'活动流',exact:true})
  await expect(feed.getByRole('alert')).toContainText('503')
  await expect(feed.getByText('暂无活动记录')).toHaveCount(0)
  await page.unroute('**/v1/observer/topic-activity?**')
  await page.getByRole('button',{name:'刷新',exact:true}).click()
  await expect(feed.locator('.topic-feed li').first()).toBeVisible()
  await expect(feed.getByRole('alert')).toHaveCount(0)
})


for (const [screen, width, height] of [['desktop',1360,900],['narrow',390,844]] as const) {
  test(`Topic navigation shows persisted delivery and Issue flows (${screen})`, async ({ page,request },info) => {
    const topics = await (await request.get(endpoint + '/v1/observer/topics')).json()
    const topic = topics.items.find((item: {title:string}) => item.title === 'Observer routing Topic')
    const facts = async (filter: string): Promise<Event[]> => {
      const response = await request.get(endpoint + '/v1/observer/topic-activity?' + new URLSearchParams({topicId:topic.id,filter,limit:'10'}))
      expect(response.ok()).toBe(true)
      return (await response.json()).items
    }
    const [messages,issues] = await Promise.all([facts('message'),facts('issue')])
    const received = messages.find(row => row.kind === 'routed_message')!
    const returned = messages.find(row => row.kind === 'route_request')!
    const report = issues.find(row => row.kind === 'report_submitted')!
    const observed = new Set<string>()
    page.on('request', req => {
      const url = new URL(req.url())
      if (url.pathname === '/v1/observer/topic-activity' && url.searchParams.get('topicId') === topic.id && !url.searchParams.has('mode')) {
        observed.add(url.searchParams.get('filter') || 'all')
        expect(req.method()).toBe('GET')
        expect(Number(url.searchParams.get('limit'))).toBeLessThanOrEqual(10)
      }
    })
    await page.setViewportSize({width,height})
    await page.goto(endpoint + '/observer/')
    await page.getByRole('navigation',{name:'观察视角'}).getByRole('link',{name:'Topic',exact:true}).click()
    const list = page.getByRole('complementary',{name:'最近的 Topic'})
    await expect(page.getByRole('region',{name:'Topic 活动流程'})).toBeVisible()
    if (screen === 'narrow') await page.getByRole('link',{name:'返回 Topic 列表'}).click()
    await list.getByRole('link',{name:new RegExp(topic.title)}).click()
    const graph = page.getByRole('region',{name:'Topic 活动流程'})
    const lane = (event: Event) => graph.locator('[data-flow-id="' + event.id + '"]')
    await expect(lane(received).locator('.flow-edge')).toContainText('投递')
    await expect(lane(received).locator('.flow-message')).toHaveAttribute('href',new RegExp(received.messageId!))
    await expect(lane(returned).locator('.flow-router')).toHaveAttribute('href',new RegExp(returned.messageId!))
    await expect(graph.locator('.flow-issue').first()).toBeVisible()
    await expect(lane(received).locator('.flow-issue')).toHaveCount(0)
    await expect(lane(returned).locator('.flow-issue')).toHaveCount(0)
    expect(observed).toEqual(new Set(['all','message','issue']))
    await graph.getByRole('button',{name:/再看/}).click()
    await expect(lane(report).locator('.flow-execution')).toContainText('Worker')
    await expect(lane(report).locator('.flow-report')).toContainText(report.summary!)
    await expect(lane(report).locator('.flow-issue')).toHaveAttribute('href',new RegExp(report.issueId!))
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(width)
    await graph.screenshot({path:info.outputPath('topic-graph-' + screen + '.png'),animations:'disabled'})
    await lane(returned).getByText('展开记录').focus()
    await page.keyboard.press('Enter')
    await expect(lane(returned).getByText('Observer return reason')).toBeVisible()
    const filters = page.getByRole('navigation',{name:'筛选活动'})
    await filters.getByRole('link',{name:'消息',exact:true}).click()
    await expect(lane(received)).toBeVisible()
    await expect(graph.locator('.flow-issue')).toHaveCount(0)
    await filters.getByRole('link',{name:'Issue',exact:true}).click()
    await expect(lane(report).locator('.flow-report')).toBeVisible()
    await expect(graph.locator('.flow-message')).toHaveCount(0)
    await lane(report).locator('.flow-issue').click()
    await expect(page).toHaveURL(new RegExp('perspective=issue.*' + report.issueId))
    await page.goBack()
    await expect(graph).toBeVisible()
    await expect(filters.getByRole('link',{name:'Issue',exact:true})).toHaveAttribute('aria-current','true')
  })
}

test('Topic diagram retains the working category when a preview read fails', async ({page,request}) => {
  const {items} = await (await request.get(endpoint + '/v1/observer/topics')).json()
  const topic = items.find((item: {title:string}) => item.title === 'Observer routing Topic')
  await page.route('**/v1/observer/topic-activity?**', route => new URL(route.request().url()).searchParams.get('filter') === 'message'
    ? route.fulfill({status:503,body:'{}'}) : route.continue())
  await page.goto(endpoint + '/observer/?perspective=topic&id=' + topic.id)
  const graph = page.getByRole('region',{name:'Topic 活动流程'})
  await expect(graph).toContainText('消息 读取失败（HTTP 503）')
  await expect(graph.locator('.flow-issue').first()).toBeVisible()
  await expect(graph.getByText('暂无消息活动记录')).toHaveCount(0)
  await page.unroute('**/v1/observer/topic-activity?**')
  await page.getByRole('button',{name:'刷新',exact:true}).click()
  await expect(graph.locator('.flow-message').first()).toBeVisible()
  await expect(graph).not.toContainText('HTTP 503')
})
