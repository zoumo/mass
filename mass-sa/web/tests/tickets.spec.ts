 await expect(detail.locator('details[data-reading="objective"]')).toHaveAttribute('open', '')
 await page.getByRole('button', { name: '关闭工作项详情', exact: true }).click()
 await page.getByLabel('搜索工作').fill('not-a-ticket')
 await page.getByRole('button', { name: '应用筛选', exact: true }).click()
 await expect(page.getByRole('heading', { name: '当前筛选没有 Ticket' })).toBeVisible()
