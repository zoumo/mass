test('history native position, pause and disclosure survive reload and back', async ({ page }) => {
  await page.goto('/observer/resources?project=alpha&selected=session-current&detailTab=history&refresh=paused')
  await expect(page.getByText('实时观察 · 持久历史已补读', { exact: true })).toBeVisible()
  await loadHistory50(page)
  await expect(page).toHaveURL(/historyWindow=page/)
  const position = new URL(page.url()).searchParams.get('historyCursor')
  await page.getByRole('button', { name: '暂停跟随' }).click()
  await expect(page).toHaveURL(/follow=paused/)
  const record = page.locator('.session-events > li > details').filter({ has: page.locator('summary', { hasText: 'historical text 50' }) })
  await record.locator(':scope > summary').click()
  await expect(record.locator('pre').first()).toHaveText('historical text 50')
  await record.locator(':scope > summary').focus()
  await page.reload()
  expect(new URL(page.url()).searchParams.get('historyCursor')).toBe(position)
  await expect(page.getByRole('button', { name: '继续跟随' })).toBeVisible()
  await expect(record).toHaveAttribute('open', '')
  await expect(record.locator(':scope > summary')).toBeFocused()
  await expect(record.locator('pre').first()).toHaveText('historical text 50')
  await page.goto('/observer/routers?refresh=paused')
  await expect(page.getByRole('heading', { name: /^(Routers|路由器)$/ })).toBeVisible()
  await page.goBack()
  await expect(record).toHaveAttribute('open', '')
  await expect(page.getByRole('button', { name: '继续跟随' })).toBeVisible()
})

