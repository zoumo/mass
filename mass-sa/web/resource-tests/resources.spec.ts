test('resource outage keeps stale list and unavailable selected identity', async ({ page }) => {
  await page.goto('/observer/resources?scope=all&refresh=paused')
  await expect(page.getByRole('link', { name: 'current', exact: true })).toBeVisible()
  await page.route('**/observer/api/sessions?*', route => route.fulfill({ status: 503, body: '{"reason":"mass_observation_unavailable"}' }))
  await page.getByRole('button', { name: '刷新查询' }).click()
  await expect(page.getByRole('heading', { name: '资源读取失败 · stale' })).toBeVisible({ timeout: 15000 })
  await expect(page.getByRole('link', { name: 'current', exact: true })).toBeVisible()
  await page.route('**/observer/api/sessions/session-current?*', route => route.fulfill({ status: 404, body: '{"reason":"not_found"}' }))
  await page.getByRole('link', { name: 'current', exact: true }).click()
  await expect(page.getByRole('heading', { name: '所选资源 unavailable', exact: true })).toBeVisible()
  await expect(page).toHaveURL(/selected=session-current/)
  await expect(page.getByRole('heading', { name: 'session-current', exact: true })).toBeVisible()
  await closeDrawer(page)
})

test('preview item aggregation, same-ID completion and bounded browser cache', async ({ page }) => {
  await trackSources(page)
  await page.goto('/observer/resources?selected=session-current&detailTab=history&refresh=paused')
  await expect(page.getByText('实时观察 · 持久历史已补读', { exact: true })).toBeVisible()
  await page.evaluate(() => {
    const sources = (window as unknown as { observerTestSources: EventSource[] }).observerTestSources
    const source = sources[sources.length - 1]!
    for (const [index, text] of ['Hello ', 'world'].entries()) {
      source.dispatchEvent(new MessageEvent('preview', { data: JSON.stringify({ eventId: `injected-${index}`, sessionId: 'session-current', itemId: 'merge-item', type: 'agent.message_chunk', time: '2026-11-16T01:00:00Z', text, payload: {}, preview: true }) }))
    }
  })
  const preview = page.locator('.session-events > li').filter({ hasText: 'Hello world' })
  await expect(preview).toHaveCount(1)
  await preview.locator(':scope > details > summary').click()
  await expect(preview.locator('pre').first()).toHaveText('Hello world')
  await page.evaluate(() => {
    const sources = (window as unknown as { observerTestSources: EventSource[] }).observerTestSources
    sources[sources.length - 1]!.dispatchEvent(new MessageEvent('history', { data: JSON.stringify({ events: [{ eventId: 'injected-0', sessionId: 'session-current', itemId: 'merge-item', type: 'agent.message', time: '2026-11-16T01:00:00Z', text: 'complete from durable history', payload: {}, preview: false }], cursor: '', earlierCursors: [], observedAt: '2026-11-16T01:00:00Z' }) }))
  })
  await expect(page.locator('.session-events > li').filter({ hasText: 'Hello world' })).toHaveCount(0)
  const complete = page.locator('.session-events > li').filter({ hasText: 'complete from durable history' })
  await expect(complete).toHaveCount(1)
  await expect(complete.getByText('持久事实', { exact: true })).toBeVisible()
  await page.evaluate(() => {
    const sources = (window as unknown as { observerTestSources: EventSource[] }).observerTestSources
    const events = Array.from({ length: 600 }, (_, i) => ({ eventId: `cache-${i}`, sessionId: 'session-current', itemId: `cache-item-${i}`, type: 'agent.message', time: '2026-11-16T01:00:00Z', text: `cache entry ${i}`, payload: {}, preview: false }))
    sources[sources.length - 1]!.dispatchEvent(new MessageEvent('history', { data: JSON.stringify({ events, cursor: '', earlierCursors: [], observedAt: '2026-11-16T01:00:00Z' }) }))
  })
  await expect(page.locator('.session-events > li > details > summary').filter({ hasText: '持久事实' })).toHaveCount(500)
  await expect(page.getByText('显示缓存已达上限', { exact: false })).toBeVisible()
})
