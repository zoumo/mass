import { expect, test } from '@playwright/test'

test('mobile selection reaches detail and returns focus to the selected row', async ({ page }) => {
  await page.setViewportSize({ width: 375, height: 812 })
  await page.goto('/observer/triggers?project=alpha&refresh=paused')
  const link = page.getByRole('link', { name: 'Router 后交 Worker', exact: true })
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await link.focus()
  await page.keyboard.press('Enter')
  const drawer = page.getByRole('dialog')
  await expect(drawer.getByRole('heading', { name: 'Router 后交 Worker', exact: true })).toBeVisible()
  await expect.poll(() => drawer.evaluate(element => element.contains(document.activeElement))).toBe(true)
  await page.screenshot({ path: 'test-results/mobile-triggers-detail.png' })
  await page.keyboard.press('Escape')
  await expect(drawer).toHaveCount(0)
  await expect(page).not.toHaveURL(/selected=/)
  await expect(link).toBeFocused()
  await page.screenshot({ path: 'test-results/mobile-detail-return.png' })
})

test('complete identity journey from Router through fixed execution to exact replies and audit', async ({ page, baseURL }) => {
  const unsafe: string[] = []
  const errors: string[] = []
  const bodies: Promise<void>[] = []
  page.on('pageerror', error => errors.push(error.message))
  page.on('request', request => {
    if (new URL(request.url()).origin !== baseURL || !['GET', 'HEAD'].includes(request.method()) || request.headers()['authorization']) unsafe.push(request.url())
  })
  page.on('response', response => {
    if (response.url().includes('/observer/api/') && !response.url().includes('/events?')) bodies.push(response.text().then(text => {
      for (const secret of ['fixture-management-secret', 'fixture-capability-secret', 'fixture-mcp-secret', 'fixture-source-secret', 'fixture-output-secret', '/private/capability-path']) expect(text).not.toContain(secret)
    }))
  })
  await page.goto('/observer/routers?project=alpha&refresh=paused&selected=alpha')
  await page.getByRole('link', { name: 'fixture-router-session', exact: true }).click()
  await expect(page).toHaveURL(/resourceTab=sessions/)
  await page.getByRole('tab', { name: '配置与身份', exact: true }).click()
  await expect(page.getByRole('dialog')).toContainText('fixture-router-session')
  await page.reload()
  await expect(page.getByRole('dialog')).toContainText('fixture-router-session')
  await page.getByRole('button', { name: '关闭资源详情', exact: true }).click()
  await page.getByRole('link', { name: '事件', exact: true }).click()
  await page.getByRole('link', { name: 'Router 后交 Worker', exact: true }).click()
  const trace = page.getByRole('region', { name: 'Trigger 追踪详情' })
  await trace.getByRole('tab', { name: '处理过程', exact: true }).click()
  await expect(trace.getByRole('region', { name: '路由入口', exact: true })).toContainText('当时匹配：无 Ticket')
  await expect(trace.getByRole('region', { name: '业务决定', exact: true })).toContainText('associate')
  const delivery = trace.getByRole('region', { name: '具体投递', exact: true })
  await expect(delivery).toContainText('fixture-router-session')
  await expect(delivery).toContainText('session-old')
  await expect(delivery).toContainText('assignment-old')
  await expect(delivery).toContainText('unknown')
  await delivery.getByRole('link', { name: 'ticket-a', exact: true }).click()
  const ticket = page.getByRole('region', { name: 'Ticket 责任详情' })
  await expect(ticket.getByRole('heading', { name: 'Fixture work A' })).toBeVisible()
  await ticket.getByRole('tab', { name: '派工与委派', exact: true }).click()
  await ticket.getByRole('region', { name: '父子委派' }).getByRole('link', { name: '联合故事孙工作', exact: true }).click()
  await expect(page).toHaveURL(/selected=t06-grandchild/)
  await expect(ticket.getByRole('heading', { name: '联合故事孙工作' })).toBeVisible()
  await page.goBack()
  await ticket.getByRole('tab', { name: '派工与委派', exact: true }).click()
  const assignments = ticket.getByRole('region', { name: 'Assignment 历史' })
  await expect(assignments.locator('details')).toHaveCount(3)
  await assignments.locator('#assignment-assignment-old').click()
  await assignments.locator('#assignment-assignment-resumed').click()
  await expect(assignments.getByRole('link', { name: 'session-old', exact: true })).toHaveCount(2)
  await assignments.getByRole('link', { name: 'session-old', exact: true }).first().click()
  await expect(page).toHaveURL(/selected=session-old/)
  const session = page.getByRole('dialog')
  await session.getByRole('tab', { name: '配置与身份', exact: true }).click()
  await expect(session).toContainText('assignment-old')
  await expect(session).toContainText('assignment-resumed')
  await expect(session).not.toContainText('assignment-current')
  await session.getByRole('tab', { name: '历史与实时', exact: true }).click()
  await expect(session.locator('.session-events > li')).toHaveCount(1)
  await session.locator('.session-events summary').first().click()
  await expect(session.locator('.session-events')).toContainText('Joint story durable history')
  await session.locator('.session-events details').first().getByText('事件身份与原始数据', { exact: true }).click()
  await expect(session.locator('.session-events')).toContainText('integrated-session-old')
  await page.getByRole('button', { name: '暂停跟随', exact: true }).click()
  await expect(page.getByRole('button', { name: '继续跟随', exact: true })).toBeVisible()
  await page.goBack()
  await expect(assignments.locator('details[data-reading="assignment-assignment-old"]')).toHaveAttribute('open', '')
  await ticket.getByRole('tab', { name: '业务事实', exact: true }).click()
  const fact = page.getByRole('article', { name: 'Output fact/ticket-a/1', exact: true })
  await fact.getByText('关联与目标详情', { exact: true }).click()
  await fact.getByText(/消费者读取与渠道确认/).click()
  await expect(fact).toContainText('output-origin')
  await expect(fact).toContainText('failed')
  await expect(fact).toContainText('unknown')
  await expect(fact).toContainText('delivered')
  await fact.getByRole('link', { name: 'output-origin', exact: true }).click()
  await expect(page).toHaveURL(/selected=output-origin/)
  await expect(page).toHaveURL(/refresh=paused/)
  const replies = page.getByRole('region', { name: '显式回复', exact: true })
  await expect(replies.getByRole('article')).toHaveCount(2)
  await expect(replies).not.toContainText('PEER_REPLY_MUST_STAY_SEPARATE')
  await expect(replies).toContainText('fact/ticket-a/1')
  await page.reload()
  await expect(replies.getByRole('article')).toHaveCount(2)
  for (const route of ['routers', 'triggers', 'tickets', 'resources']) {
    const response = await page.request.get(`/observer/${route}?project=alpha`)
    expect(response.status()).toBe(200)
    expect(await response.text()).toContain('/observer/assets/')
  }
  await Promise.all(bodies)
  expect(unsafe).toEqual([])
  expect(errors).toEqual([])
  expect(await page.locator('body').innerText()).not.toContain('fixture-management-secret')
})
