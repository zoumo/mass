package schema

import (
	"entgo.io/ent"
	"entgo.io/ent/dialect/entsql"
	"entgo.io/ent/schema"
	"entgo.io/ent/schema/field"
	"entgo.io/ent/schema/index"
)

// ScheduledTask maps the SQLite columns in core/schema/0028.sql.
// SQLite owns the generated business ID and JSON-derived columns.
type ScheduledTask struct{ ent.Schema }

func (ScheduledTask) Fields() []ent.Field {
	return []ent.Field{
		field.Int64("id").StorageKey("seq"),
		field.String("business_id").StorageKey("id").Unique().Optional().Immutable(),
		field.Enum("owner_type").Values("topic").Optional().Immutable(),
		field.String("owner_id").Optional().Immutable(),
		field.Int("topic_generation").Default(0).Immutable(),
		field.String("created_at").Immutable(),
		field.String("schedule_anchor"),
		field.String("deleted_at").Optional(),
		field.Bytes("body"),
		field.Enum("status").Values("active", "paused", "completed").Optional().Immutable(),
		field.String("next_run_at").Optional().Immutable(),
		field.String("creation_key").Unique().Immutable(),
		field.String("creation_digest").Immutable(),
	}
}

func (ScheduledTask) Annotations() []schema.Annotation {
	return []schema.Annotation{
		entsql.Table("scheduled_tasks"),
		// Core installs its own DDL, including columns generated by SQLite and
		// an owner foreign key to the Topic business ID.
		entsql.Skip(),
	}
}

func (ScheduledTask) Indexes() []ent.Index {
	return []ent.Index{
		index.Fields("owner_type", "owner_id", "created_at", "business_id").
			StorageKey("scheduled_tasks_owner").Annotations(entsql.IndexWhere("deleted_at IS NULL")),
		index.Fields("next_run_at", "id").
			StorageKey("scheduled_tasks_due").Annotations(entsql.IndexWhere("status='active' AND deleted_at IS NULL")),
	}
}
