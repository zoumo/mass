test('five second polling preserves open detail and pause disables repeated queries', async ({ page }) => {
 const queries: string[] = []
 page.on('request', request => { if (request.url().includes('/observer/api/tickets')) queries.push(request.url()) })
 await page.goto('/observer/tickets?project=alpha&selected=t03-root&selectedProject=alpha')
 const detail = page.getByRole('region', { name: 'Ticket 责任详情' })
 await expect(detail.getByRole('heading', { name: '责任核对主工作', exact: true })).toBeVisible()
 await detail.getByText('展开目标（文本）', { exact: true }).click()
 const initial = queries.length
 await expect.poll(() => queries.length, { timeout: 8500 }).toBeGreaterThan(initial)
 await expect(detail.locator('details[data-reading="objective"]')).toHaveAttribute('open', '')
 await expect(page).toHaveURL(/selected=t03-root/)
 await page.goto('/observer/tickets?project=alpha&selected=t03-root&selectedProject=alpha&refresh=paused')
 await expect(detail.getByRole('heading', { name: '责任核对主工作', exact: true })).toBeVisible()
 await page.waitForLoadState('networkidle')
 const paused = queries.length
 await page.waitForTimeout(5500)
 expect(queries.length).toBe(paused)
})


