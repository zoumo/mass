import { expect, test } from '@playwright/test'

test.use({ baseURL: 'http://127.0.0.1:' + (process.env.SUPERAGENT_ROUTING_BROWSER_PORT || '18794') })

test('Issue shows blockers and report provenance before explicit acceptance', async ({ page, request }, testInfo) => {
  const issues = (await (await request.get('/v1/observer/issues')).json()).items
  const blocked = issues.find((r: {title: string}) => r.title === 'Review blocked build')
  await page.goto('/observer/?perspective=issue&id=' + blocked.id)
  const issue = page.getByRole('article', { name: '当前 Issue' })
  await expect(issue.getByRole('heading', {name: blocked.title})).toBeVisible()
  await expect(issue.getByText('Confirm the archive with the reviewer', {exact:false})).toBeVisible()
  await expect(issue.getByRole('button', {name:/Topic 已验收/})).toHaveCount(0)
  const graph = issue.getByRole('region', { name: 'Issue 进展流程' })
  const run = graph.locator('li').filter({has: page.getByRole('link', {name: '报告 Archive review in progress'})})
  await expect(run).toContainText('第 1 轮')
  await expect(run).toContainText('Issue Session 提交')
  await expect(graph.getByText('业务验收', {exact: true})).toHaveCount(0)
  await issue.getByRole('button', {name:/Issue Session 提交报告/}).click()
  await expect(issue.getByText('第 1 轮执行 · 目标版本 1')).toBeVisible()
  await issue.getByRole('button', {name:'启动第 1 轮执行'}).click()
  await expect(issue.getByRole('link',{name:'Archive review in progress', exact:true})).toBeVisible()
  await expect(issue.getByText('启动事件 · Session 已受理')).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('issue-desktop.png'), fullPage:true})
  await issue.getByRole('button', {name:'Topic 发出目标修订通知'}).click()
  await expect(issue.getByText('目标版本 2 · Session 已受理')).toBeVisible()
  const scoped = await request.get('/v1/observer/internal-events?preview=true&issueId=' + blocked.id)
  expect(scoped.ok()).toBeTruthy()
  const {items} = await scoped.json()
  expect(items.some((d:{goalUpdate:boolean}) => d.goalUpdate)).toBeTruthy()
  for (const d of items) expect(d.refs.some((r:{kind:string;id:string;issue_id?:string}) => r.kind === 'issue' ? r.id === blocked.id : r.issue_id === blocked.id)).toBeTruthy()
  const href = page.url()
  await issue.getByRole('link',{name:'查看依赖 Issue'}).click()
  await issue.getByRole('button',{name:'Topic 已验收'}).click()
  await expect(issue.getByText('Reviewed the sample build log')).toBeVisible()
  await expect(issue.getByText('artifacts/build.log')).toBeVisible()
  await page.goBack()
  await expect(page).toHaveURL(href)
  await expect(issue.getByRole('heading', {name:blocked.title})).toBeVisible()
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByRole('link',{name:'返回 Issue 列表'})).toBeVisible()
  await page.screenshot({path:testInfo.outputPath('issue-narrow.png'),fullPage:true})
  expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBe(390)
})

test('narrow Issue list restores focus and history to the selected row', async ({ page }) => {
  await page.setViewportSize({ width: 390, height: 844 })
  await page.goto('/observer/?perspective=issue')
  await page.getByRole('link', { name: '返回 Issue 列表' }).click()
  const listURL = page.url()
  const row = page.getByRole('complementary', { name: '最近的 Issue' }).getByRole('link').nth(1)
  await expect(row).toBeVisible()
  const href = await row.getAttribute('href')
  await row.click()
  await expect(page.getByRole('region', { name: 'Issue 详情' })).toBeFocused()
  await page.getByRole('link', { name: '返回 Issue 列表' }).click()
  await expect(page).toHaveURL(listURL)
  await expect(row).toBeFocused()
  await page.goForward()
  await expect(page).toHaveURL(new URL(href!, listURL).href)
})
